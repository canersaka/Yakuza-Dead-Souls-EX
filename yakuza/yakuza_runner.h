/*
 * Yakuza: Dead Souls -- recomp runner, shared declarations.
 *
 * Translation-unit layout:
 *   - main.cpp / dispatch.cpp / func_table_gen.cpp include the generated
 *     ppu_recomp.h.
 *   - shims.cpp includes the runtime headers instead.
 *   Both define the same ppu_context, so this header only forward-declares it.
 */
#pragma once

#include <stdint.h>
#include <stddef.h>

struct ppu_context;
typedef struct ppu_context ppu_context;

typedef void (*yz_ppu_fn)(ppu_context*);

/* Live guest context for the current host thread (defined in main.cpp). Set at
 * each guest-thread entry / callback so the crash handler can walk the guest
 * PPC64 back-chain. */
extern thread_local ppu_context* g_yz_cur_ctx;

/* Generated by gen_func_table.py -- sorted by addr, no sentinel. */
struct yz_func_entry {
    uint32_t addr;
    yz_ppu_fn fn;
};
extern const yz_func_entry g_yz_func_table[];
extern const unsigned      g_yz_func_count;

/* dispatch.cpp */
extern "C" yz_ppu_fn yz_lookup_func(uint32_t guest_addr);   /* NULL if unknown */
/* threads.cpp: give a host service thread a distinct guest-visible tid (band
 * 0xE0+) instead of the thread-local default 1 (= the main guest thread). */
extern "C" uint32_t yz_thread_adopt_host(const char* name);
extern "C" void      yz_drain_trampolines(ppu_context* ctx);
/* Call a guest function through an OPD descriptor (sets r2, drains). */
extern "C" void      yz_call_guest_opd(uint32_t opd_addr, ppu_context* ctx);

/* shims.cpp */
extern "C" void yz_init_syscalls(void);

/* threads.cpp -- PPU thread runtime */
extern "C" void     yz_threads_init(uint32_t main_stack_base,
                                    uint32_t main_stack_size);
extern "C" uint32_t yz_thread_current_id(void);
/* lv2 wait recorder: shims.cpp records the in-flight syscall per thread and
 * the stall dump (main.cpp) reads it to name what each thread blocks on. */
extern "C" void yz_wait_enter(uint32_t num, uint64_t a3, uint64_t a4, uint64_t a5);
extern "C" void yz_wait_exit(void);
extern "C" int  yz_wait_get(uint32_t tid, uint32_t* num, uint64_t* a3,
                            uint64_t* a4, uint64_t* a5, uint32_t* held_ms);
extern "C" int64_t  yz_sc_thread_yield(ppu_context* ctx);
extern "C" int64_t  yz_sc_thread_join(ppu_context* ctx);
extern "C" int64_t  yz_sc_thread_detach(ppu_context* ctx);
extern "C" int64_t  yz_sc_thread_get_join_state(ppu_context* ctx);
extern "C" int64_t  yz_sc_thread_set_priority(ppu_context* ctx);
extern "C" int64_t  yz_sc_thread_get_priority(ppu_context* ctx);
extern "C" int64_t  yz_sc_thread_get_stack_information(ppu_context* ctx);

/* import_bridges_gen.cpp (generated by gen_imports.py) -----------------------
 * Each imported system-library function gets a synthetic OPD in guest scratch
 * memory whose code address is a fake key that routes ps3_indirect_call to
 * a host bridge. The fake range is never dereferenced as memory. */
#define YZ_IMPORT_OPD_BASE  0x0FF00000u
#define YZ_IMPORT_FAKE_BASE 0xFE000000u
extern "C" void  yz_install_imports(void);
extern yz_ppu_fn g_yz_import_bridges[];
extern const unsigned g_yz_import_count;
extern const char* const g_yz_import_names[];

/* gcm guest-side structures (import_overrides.cpp) ----------------------------
 * _cellGcmInitBody builds these in runner scratch. The game's inline gcm code
 * walks CellGcmContextData in guest memory itself: begin@+0, end@+4,
 * current@+8, callback@+0xC; the callback field holds an OPD whose code word
 * the game mtctr/bctrl's. */
#define YZ_GCM_CTX_ADDR     0x0FF80000u  /* CellGcmContextData (16 B) */
#define YZ_GCM_CB_OPD_ADDR  0x0FF80020u  /* synthetic OPD for the fifo callback */
#define YZ_GCM_CB_FAKE_KEY  0xFE100000u  /* routed by import_bridge_for() */
#define YZ_GCM_LOCAL_BASE   0xC0000000u  /* RSX local memory (matches libs) */
#define YZ_GCM_LOCAL_SIZE   0x0F900000u  /* 249 MB, real-hardware value */
extern "C" void yz_gcm_fifo_callback(ppu_context* ctx);

/* sys_rsx syscalls (lv2 668-677) -- Sony's libgcm drives the RSX through these.
 * Implemented in import_overrides.cpp (alongside the FIFO consumer they feed),
 * registered into the lv2 table by yz_init_syscalls (shims.cpp). */
extern "C" int64_t yz_sys_rsx_memory_allocate(ppu_context* ctx);   /* 668 0x29C */
extern "C" int64_t yz_sys_rsx_memory_free(ppu_context* ctx);       /* 669 0x29D */
extern "C" int64_t yz_sys_rsx_context_allocate(ppu_context* ctx);  /* 670 0x29E */
extern "C" int64_t yz_sys_rsx_context_free(ppu_context* ctx);      /* 671 0x29F */
extern "C" int64_t yz_sys_rsx_context_iomap(ppu_context* ctx);     /* 672 0x2A0 */
extern "C" int64_t yz_sys_rsx_context_iounmap(ppu_context* ctx);   /* 673 0x2A1 */
extern "C" int64_t yz_sys_rsx_context_attribute(ppu_context* ctx); /* 674 0x2A2 */
extern "C" int64_t yz_sys_rsx_device_map(ppu_context* ctx);        /* 675 0x2A3 */
extern "C" int64_t yz_sys_rsx_device_unmap(ppu_context* ctx);      /* 676 0x2A4 */
extern "C" int64_t yz_sys_rsx_attribute(ppu_context* ctx);         /* 677 0x2A5 */
/* Host vblank tick: publishes flip completion + vBlank counters (defined in
 * yz_sys_rsx.inc, called from main.cpp's vblank thread). */
extern "C" void yz_rsx_vblank_tick(void);
