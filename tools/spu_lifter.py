# Region lifting
# ---------------------------------------------------------------------------

@dataclass
class RegionLift:
    header: str
    source: str
    regions: list[tuple[int, int]]
    n_insns: int
    errors: list[str]            # anything that makes the lift unsafe to ship
    cross_image_targets: list[int]
    data_words: int


def elf_region_starts(insns: list[SPUInstruction]) -> set:
    """Region split points for an image lifted from an ELF: brsl/brasl call
    targets and the return points of indirect calls. Plain branch targets do
    not split regions; every pc remains an entry case of its region."""
    from find_spu_functions import collect_brsl_targets
    starts = set(collect_brsl_targets(insns))
    for ins in insns:
        if ins.mnemonic in ("bisl", "bisld", "bisle"):
            starts.add(ins.addr + 4)
    return starts


def lift_regions(insns: list[SPUInstruction], logical_bounds, region_starts: set, *,
                 region_prefix: str, register_name: str, header_name: str,
                 region_cap: int = 256, skip_calls: dict | None = None,
                 includes=()) -> RegionLift:
    """Region-lift one image. `logical_bounds` are the detected function
    bounds (used to classify `bi $r0`); `region_starts` are the split points."""
    lifter = SPULifter()
    lifter.header_name = header_name
    lifter.register_name = register_name
    lifter.region_prefix = region_prefix
    lifter.skip_calls = dict(skip_calls or {})
    lifter.includes = list(includes)
    lifter.bi_r0_jump = compute_bi_r0_jumps(insns, logical_bounds)
    addrs = sorted(i.addr for i in insns)
    lifter.image_span = (addrs[0], addrs[-1] + 4) if addrs else None

    regions = form_regions(insns, region_starts, region_cap)
    starts = [rs for rs, _re in regions]
    pc_to_region = {a: starts[bisect_right(starts, a) - 1] for a in addrs}
    for rs, re_ in regions:
        lifter.lift_region(insns, rs, re_, pc_to_region)
    header = lifter.emit_region_header()
    source = lifter.emit_region_source(pc_to_region)

    errors = []
    for site in sorted(set(lifter.skip_calls) - lifter.skipped_calls):
        errors.append(f"skip_calls entry 0x{site:X} matched no instruction")
    for s_, t in lifter.region_fallback_internal:
        errors.append(f"in-image target 0x{t:X} (from 0x{s_ or 0:X}) missing from the region map")
    for a in lifter.unresolved_calls:
        errors.append(f"call at 0x{a:X} has no resolvable target")
    for mn, n in sorted(lifter.unsupported.items()):
        if mn != ".word":   # data embedded in .text, never executed
            errors.append(f"{n} unsupported '{mn}' instruction(s)")
    # Emitter invariant: every trampoline hand-off stores ctx->pc first on the
    # same line, because the receiving region's entry switch consumes it.
    for n, line in enumerate(source.splitlines(), 1):
        at = line.find("g_spu_trampoline_fn =")
        if at >= 0 and "ctx->pc = " not in line[:at]:
            errors.append(f"line {n}: trampoline hand-off without a pc store")

    return RegionLift(
        header=header, source=source, regions=regions, n_insns=len(insns),
        errors=errors,
        cross_image_targets=sorted({t for _s, t in lifter.region_fallback_external}),
        data_words=lifter.unsupported.get(".word", 0))


