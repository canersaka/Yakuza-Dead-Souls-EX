#!/usr/bin/env python3
"""Lift the game's SPU programs into C.

Reads the SPU manifest (yakuza/spu_images.json) and the decrypted EBOOT, and
writes yakuza/generated/spu/:

  <stem>.c, <stem>.h   the region-lifted code of one placement
  spu_images.h         the task image, job binary and job placement tables
  spu_images.c         the tables and spu_register_lifted_images()

Every input comes from the EBOOT: task images are SPU ELFs embedded in it, job
binaries are raw slices of it, lifted once per local-store base they run at.
Before lifting, the manifest is checked against the EBOOT so that no SPU
payload goes unaccounted for.

Usage, from the repository root:
    py -3 tools/gen_spu_images.py [--eboot game/EBOOT.elf] [--manifest FILE]
                                  [--only STEM,...] [--jobs N]
"""

import argparse
import json
import os
import struct
import sys
from concurrent.futures import ProcessPoolExecutor
from dataclasses import dataclass, field

TOOLS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS)
sys.path.insert(0, TOOLS)

from elf_parser import ELFFile, vaddr_to_offset                      # noqa: E402
from extract_spu_images import find_spu_images, parse_spu_elf_size   # noqa: E402
from wrap_spu_elf import wrap                                        # noqa: E402

MANIFEST = os.path.join(ROOT, "yakuza", "spu_images.json")
OUT_DIR = os.path.join(ROOT, "yakuza", "generated", "spu")
BANNER = "/* Generated by tools/gen_spu_images.py from yakuza/spu_images.json -- do not edit. */"
MAX_PADDING = 0x400     # largest gap tolerated between SPU payloads in the EBOOT


@dataclass
class Placement:
    stem: str
    image_id: int
    binary: str
    is_job: bool = False
    elf: bytes = b""                 # the lifter input (a wrapped ELF for jobs)
    base: int = 0
    entry: int = 0
    span: int = 0
    skip_calls: dict = field(default_factory=dict)
    includes: list = field(default_factory=list)


class Eboot:
    def __init__(self, path):
        self.elf = ELFFile(path)
        self.elf.load()
        self.data = self.elf.raw_data

    def offset(self, ea):
        off = vaddr_to_offset(self.elf.program_headers, ea)
        if off is None:
            raise SystemExit(f"EA 0x{ea:08X} is not inside the EBOOT")
        return off

    def ea(self, offset):
        for ph in self.elf.program_headers:
            if ph.p_filesz and ph.p_offset <= offset < ph.p_offset + ph.p_filesz:
                return ph.p_vaddr + (offset - ph.p_offset)
        return None

    def read(self, ea, size):
        off = self.offset(ea)
        return self.data[off:off + size]

    def spu_elf(self, ea):
        off = self.offset(ea)
        size = parse_spu_elf_size(self.data, off)
        if not size:
            raise SystemExit(f"no SPU ELF at EA 0x{ea:08X}")
        return self.data[off:off + size]

    def section(self, ea):
        for sh in self.elf.section_headers:
            if sh.sh_size and sh.sh_addr <= ea < sh.sh_addr + sh.sh_size:
                return sh
        return None


def spu_elf_layout(elf):
    """(load address, loaded size, entry) of an SPU ELF's first PT_LOAD."""
    entry, phoff = struct.unpack_from(">II", elf, 24)
    phnum = struct.unpack_from(">H", elf, 44)[0]
    for i in range(phnum):
        p_type, _off, vaddr, _pa, filesz = struct.unpack_from(">5I", elf, phoff + i * 32)
        if p_type == 1:
            return vaddr, filesz, entry
    raise SystemExit("SPU ELF without a PT_LOAD segment")


def num(value):
    return int(value, 0) if isinstance(value, str) else int(value)


def load_placements(manifest, eboot):
    binaries = manifest["binaries"]
    placements, seen = [], set()
    for spec in manifest["images"]:
        stem = spec["stem"]
        if stem in seen:
            raise SystemExit(f"duplicate image stem {stem}")
        seen.add(stem)
        name = spec.get("binary", stem)
        if name not in binaries:
            raise SystemExit(f"{stem}: unknown binary {name}")
        binary = binaries[name]
        p = Placement(stem=stem, image_id=spec["image_id"], binary=name,
                      skip_calls={num(pc): cond for pc, cond in spec.get("skip_calls", {}).items()},
                      includes=list(spec.get("includes", [])))
        if "elf" in binary:
            if "base" in spec:
                raise SystemExit(f"{stem}: a task image loads at its ELF address; drop 'base'")
            p.elf = eboot.spu_elf(num(binary["elf"]))
            p.base, p.span, p.entry = spu_elf_layout(p.elf)
        else:
            p.is_job = True
            p.base = p.entry = num(spec["base"])
            code = eboot.read(num(binary["ea"]), num(binary["size"]))
            p.elf = wrap(code, base=p.base, entry=p.base)
            p.span = len(code)
        placements.append(p)
    return placements


def check_manifest(manifest, placements, eboot):
    """Reject a manifest the runtime could not serve unambiguously, or one
    that leaves SPU payloads in the EBOOT unaccounted for."""
    errors = []
    binaries = manifest["binaries"]

    # Lookups are keyed by (image id, pc): placements sharing an id must not
    # overlap in local store.
    by_id = {}
    for p in placements:
        for q in by_id.get(p.image_id, []):
            if p.base < q.base + q.span and q.base < p.base + p.span:
                errors.append(f"{p.stem} and {q.stem} overlap in local store but share image id {p.image_id}")
        by_id.setdefault(p.image_id, []).append(p)
    for p in placements:
        if p.image_id == 0 and p is not placements[-1]:
            errors.append(f"{p.stem}: image 0 matches any lookup and must be registered last")

    used = {p.binary for p in placements}
    for name, binary in binaries.items():
        if name not in used:
            errors.append(f"binary {name} has no placement")
        if "ea" in binary:
            ids = {p.image_id for p in placements if p.binary == name}
            if binary.get("image_id") not in ids:
                errors.append(f"binary {name}: image_id {binary.get('image_id')} is none of its placements' ids")

    # Every SPU ELF embedded in the EBOOT must be listed.
    listed = {num(b["elf"]) for b in binaries.values() if "elf" in b}
    for offset, _size in find_spu_images(eboot.data):
        ea = eboot.ea(offset)
        if ea is not None and ea not in listed:
            errors.append(f"SPU ELF at EA 0x{ea:08X} is not in the manifest")

    # The payloads are packed into one section; a large unexplained gap there
    # is a job binary the manifest is missing.
    spans = []
    for name, b in binaries.items():
        if "elf" in b:
            spans.append((num(b["elf"]), num(b["elf"]) + len(eboot.spu_elf(num(b["elf"]))), name))
        else:
            size = max([num(b["size"])] + [num(s) for s in b.get("identity_sizes", [])])
            spans.append((num(b["ea"]), num(b["ea"]) + size, name))
    sections = {}
    for lo, hi, name in spans:
        sh = eboot.section(lo)
        if sh is None or hi > sh.sh_addr + sh.sh_size:
            errors.append(f"binary {name} does not lie within one EBOOT section")
            continue
        sections.setdefault((sh.sh_addr, sh.sh_size), []).append((lo, hi))
    for (addr, size), ranges in sections.items():
        cursor = addr
        for lo, hi in sorted(ranges) + [(addr + size, addr + size)]:
            if lo - cursor > MAX_PADDING:
                errors.append(f"unaccounted SPU payload bytes at EA 0x{cursor:08X}-0x{lo:08X}")
            cursor = max(cursor, hi)

    if errors:
        raise SystemExit("manifest check failed:\n  " + "\n  ".join(errors))


def write_if_changed(path, text):
    """Leave an up-to-date file untouched so the build does not recompile it."""
    try:
        with open(path, encoding="utf-8", newline="") as f:
            if f.read() == text:
                return
    except FileNotFoundError:
        pass
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def lift(p):
    """Region-lift one placement and write its source and header."""
    from find_spu_functions import detect_functions
    from spu_disasm import disassemble_spu
    from spu_lifter import elf_region_starts, lift_regions

    funcs, (text_off, base, size) = detect_functions(p.elf, verbose=False)
    insns = disassemble_spu(p.elf[text_off:text_off + size], base)
    result = lift_regions(insns, funcs, elf_region_starts(insns),
                          region_prefix=f"spu_{p.stem}_",
                          register_name=f"spu_register_{p.stem}",
                          header_name=f"{p.stem}.h",
                          skip_calls=p.skip_calls, includes=p.includes)
    if not result.errors:
        write_if_changed(os.path.join(OUT_DIR, f"{p.stem}.h"), result.header)
        write_if_changed(os.path.join(OUT_DIR, f"{p.stem}.c"), result.source)
    return p.stem, len(result.regions), result.n_insns, result.errors


def write_tables(manifest, placements):
    binaries = manifest["binaries"]
    tasks = sorted((p for p in placements if not p.is_job), key=lambda p: num(binaries[p.binary]["elf"]))
    job_binaries = []
    for name, b in binaries.items():
        if "ea" in b:
            for size in b.get("identity_sizes", [b["size"]]):
                job_binaries.append((num(b["ea"]), num(size), b["image_id"], name))

    header = [BANNER, "#pragma once", "#include <stdint.h>", "",
              "#ifdef __cplusplus", 'extern "C" {', "#endif", "",
              "/* SPURS task images: SPU ELFs embedded in the EBOOT. */",
              "typedef struct spu_task_image {",
              "    uint32_t elf_ea;     /* EBOOT address of the ELF */",
              "    int image_id;",
              "    uint32_t entry;      /* ELF entry point */",
              "    const char* name;",
              "} spu_task_image;", "",
              "/* SPURS job binaries, by the address and length job descriptors publish. */",
              "typedef struct spu_job_binary {",
              "    uint32_t ea;",
              "    uint32_t size;",
              "    int image_id;        /* the image id a launch adopts */",
              "    const char* name;",
              "} spu_job_binary;", "",
              "extern const spu_task_image g_spu_task_images[];",
              "extern const unsigned g_spu_task_image_count;",
              "extern const spu_job_binary g_spu_job_binaries[];",
              "extern const unsigned g_spu_job_binary_count;", "",
              "/* Register every lifted placement for dispatch, in manifest order, and the",
              " * placement table that job launches select from. */",
              "void spu_register_lifted_images(void);", "",
              "#ifdef __cplusplus", "}", "#endif", ""]

    source = [BANNER, '#include "spu_images.h"', '#include "spu_job_dispatch.h"', "",
              "const spu_task_image g_spu_task_images[] = {"]
    source += [f'    {{ 0x{num(binaries[p.binary]["elf"]):08X}u, {p.image_id}, 0x{p.entry:X}u, "{p.stem}" }},'
               for p in tasks]
    source += ["};", f"const unsigned g_spu_task_image_count = {len(tasks)};", "",
               "const spu_job_binary g_spu_job_binaries[] = {"]
    source += [f'    {{ 0x{ea:08X}u, 0x{size:X}u, {image_id}, "{name}" }},'
               for ea, size, image_id, name in job_binaries]
    source += ["};", f"const unsigned g_spu_job_binary_count = {len(job_binaries)};", "",
               "static const spu_job_placement k_job_placements[] = {"]
    jobs = [p for p in placements if p.is_job]
    source += [f"    {{ 0x{num(binaries[p.binary]['ea']):08X}u, 0x{p.base:05X}u, {p.image_id} }},  /* {p.stem} */"
               for p in jobs]
    source += ["};", "", "void spu_begin_image(int image_id);"]
    source += [f"void spu_register_{p.stem}(void);" for p in placements]
    source += ["", "void spu_register_lifted_images(void)", "{",
               f"    spu_job_placements_set(k_job_placements, {len(jobs)}u);"]
    source += [f"    spu_begin_image({p.image_id}); spu_register_{p.stem}();" for p in placements]
    source += ["}", ""]

    for name, lines in (("spu_images.h", header), ("spu_images.c", source)):
        write_if_changed(os.path.join(OUT_DIR, name), "\n".join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--eboot", default=os.path.join(ROOT, "game", "EBOOT.elf"))
    ap.add_argument("--manifest", default=MANIFEST)
    ap.add_argument("--only", help="comma-separated stems to relift (tables are always rewritten)")
    ap.add_argument("--jobs", type=int, default=os.cpu_count())
    args = ap.parse_args()

    manifest = json.load(open(args.manifest, encoding="utf-8"))
    eboot = Eboot(args.eboot)
    placements = load_placements(manifest, eboot)
    check_manifest(manifest, placements, eboot)

    todo = placements
    if args.only:
        wanted = set(args.only.split(","))
        todo = [p for p in placements if p.stem in wanted]
        if len(todo) != len(wanted):
            raise SystemExit(f"unknown stem(s): {', '.join(sorted(wanted - {p.stem for p in todo}))}")
    os.makedirs(OUT_DIR, exist_ok=True)

    failed = 0
    with ProcessPoolExecutor(max_workers=args.jobs) as pool:
        for stem, n_regions, n_insns, errors in pool.map(lift, todo):
            print(f"{stem:24s} {n_regions:5d} regions {n_insns:7d} instructions")
            for e in errors:
                print(f"    error: {e}")
            failed += bool(errors)
    write_tables(manifest, placements)
    if failed:
        raise SystemExit(f"{failed} placement(s) failed to lift")
    if not args.only:
        wanted = {"spu_images.h", "spu_images.c"}
        wanted |= {f"{p.stem}.{ext}" for p in placements for ext in ("c", "h")}
        for name in sorted(set(os.listdir(OUT_DIR)) - wanted):
            os.remove(os.path.join(OUT_DIR, name))
            print(f"removed stale {name}")
    print(f"{len(todo)} placement(s) lifted into {os.path.relpath(OUT_DIR, ROOT)}")


if __name__ == "__main__":
    main()
